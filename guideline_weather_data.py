def get_weather_non_work_days(station, start_date, end_date, conditions=None):
    """
    지정 기간·지점·조건 조합의 기상 비작업일수(A)를 계산.

    가이드라인 표는 '월평균 비작업일수'이므로, 부분 월은 일수 비례로 안분한다.
    여러 조건을 선택하면 단순 합산한다(가이드라인 산정서와 동일 방식 —
    조건 간 중복은 별도 보정하지 않음).

    Args:
        station (str): "경상북도 의성" 형태의 지점명
        start_date, end_date (datetime|date)
        conditions (iterable[str]): 조건 키 목록. None이면 DEFAULT_CONDITIONS

    Returns:
        dict: {"total": float, "by_condition": {키: 일수}, "monthly": [...]}
    """
    from calendar import monthrange
    from datetime import datetime, date

    if not station or not start_date or not end_date:
        return {"total": 0.0, "by_condition": {}, "monthly": []}

    def _d(x):
        if isinstance(x, datetime):
            return x.date()
        if isinstance(x, date):
            return x
        return datetime.strptime(str(x), "%Y-%m-%d").date()

    s, e = _d(start_date), _d(end_date)
    if e < s:
        return {"total": 0.0, "by_condition": {}, "monthly": []}

    conds = list(conditions) if conditions else list(DEFAULT_CONDITIONS)
    conds = [c for c in conds if c in WEATHER_NON_WORK]

    by_cond = {c: 0.0 for c in conds}
    monthly = []

    y, m = s.year, s.month
    while (y, m) <= (e.year, e.month):
        dim = monthrange(y, m)[1]
        first = 1 if (y, m) != (s.year, s.month) else s.day
        last = dim if (y, m) != (e.year, e.month) else e.day
        days = max(0, last - first + 1)
        ratio = days / dim if dim else 0

        row = {"월": f"{y}-{m:02d}", "일수": days}
        msum = 0.0
        for c in conds:
            table = WEATHER_NON_WORK.get(c, {})
            v = table.get(station)
            val = (v[m - 1] * ratio) if v else 0.0
            by_cond[c] += val
            row[CONDITION_LABELS.get(c, c)] = round(val, 2)
            msum += val
        row["합계"] = round(msum, 2)
        monthly.append(row)

        m += 1
        if m > 12:
            m = 1
            y += 1

    return {
        "total": round(sum(by_cond.values()), 1),
        "by_condition": {k: round(v, 1) for k, v in by_cond.items()},
        "monthly": monthly,
    }